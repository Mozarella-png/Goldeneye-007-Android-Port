#!/usr/bin/env python3
"""Generate app/src/main/cpp/port.cmake from the PC build's CMakeLists.txt.

The PC build (CMakeLists.txt at the repo root) is the source of truth for the
game's source lists, compile definitions, include paths and configure_file
steps. This copies the relevant top-level CMake commands verbatim, rewriting
only the root variables so the Android build can use them:

    ${CMAKE_SOURCE_DIR}  -> ${GE_ROOT}   (repo root, from the Android CMake)
    ${CMAKE_BINARY_DIR}  -> ${GE_BIN}    (Android build dir)

Re-run after changing the PC build:  python3 tools_pc/android/gen_port_cmake.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "CMakeLists.txt"
OUT = ROOT / "app" / "src" / "main" / "cpp" / "port.cmake"

# Commands we need, identified by a substring of their text.
WANTED = [
    "add_definitions(",
    "add_compile_options(",
    "include_directories(\n  \"${CMAKE_SOURCE_DIR}/port/shim\"",
    "configure_file(",              # all of them (port/include/*.in)
    "file(GLOB_RECURSE SRC_GAME",
    "list(REMOVE_ITEM SRC_GAME",
    "file(GLOB SRC_LIBAUDIO",
    "file(GLOB SRC_LIBULTRARE_AUDIO",
    "file(GLOB SRC_GU",
    "set(SRC_LIBULTRARE_DATA",
    "list(PREPEND SRC_LIBULTRARE_DATA",
    "set(SRC_LIBULTRARE_LIBC",
    "list(PREPEND SRC_LIBULTRARE_LIBC",
    "set(SRC_ROMASSETS",
    "set(SRC_DRAM_SYMS",
    "set(SRC_ASSETS",
    "list(PREPEND SRC_ASSETS",
    "set(SRC_ENGINE",
    "list(PREPEND SRC_ENGINE",
]

def statements(text):
    """Yield (start_line_index, full_statement_text) for top-level commands."""
    lines = text.split("\n")
    i = 0
    while i < len(lines):
        line = lines[i]
        m = re.match(r"^[A-Za-z_]+\(", line)
        if not m or line.lstrip().startswith("#"):
            i += 1
            continue
        start = i
        depth = 0
        buf = []
        while i < len(lines):
            # strip comments outside strings (simple: a '#' not inside quotes)
            l = lines[i]
            out, q = "", False
            for ch in l:
                if ch == '"':
                    q = not q
                if ch == "#" and not q:
                    break
                out += ch
            buf.append(l)
            depth += out.count("(") - out.count(")")
            i += 1
            if depth <= 0 and out.strip():
                break
        yield start, "\n".join(buf)

def main():
    text = SRC.read_text(encoding="utf-8")
    picked = []
    seen = set()
    for idx, stmt in statements(text):
        if any(w in stmt for w in WANTED) and idx not in seen:
            seen.add(idx)
            picked.append(stmt)
    if not picked:
        print("no commands matched; root CMakeLists changed?", file=sys.stderr)
        return 1

    body = "\n\n".join(picked)
    body = body.replace("${CMAKE_SOURCE_DIR}", "${GE_ROOT}")
    body = body.replace("${CMAKE_BINARY_DIR}", "${GE_BIN}")
    header = (
        "# GENERATED by tools_pc/android/gen_port_cmake.py from ../../CMakeLists.txt.\n"
        "# Do not edit by hand. Included by app/src/main/cpp/CMakeLists.txt when\n"
        "# GE_BUILD_PORT=ON. Expects: GE_ROOT (repo root), GE_BIN (build dir),\n"
        "# VERSION_IS_PAL, REGION_DEFS, ASSET_REGION, TARGET_IS_64BIT.\n\n"
    )
    OUT.write_text(header + body + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(picked)} commands)")
    return 0

if __name__ == "__main__":
    sys.exit(main())
